def reduce(n: int) -> int:
    while n > 22:
        n = sum(int(d) for d in str(n))
    return n or 22


def parse_date(s: str) -> dt.date:
    d = dt.date.fromisoformat(s)
    if not (dt.date(1900, 1, 1) <= d <= dt.date.today()):
        raise ValueError("bad date")
    return d


def points(d: dt.date) -> dict[str, int]:
    a = reduce(d.day)
    b = reduce(d.month)
    c = reduce(sum(int(x) for x in str(d.year)))
    dd = reduce(a + b + c)
    e = reduce(a + b + c + dd)
    return {"a": a, "b": b, "c": c, "d": dd, "e": e, "love": reduce(a + e), "purpose": reduce(b + dd)}


def card(n: int) -> dict:
    name, cid = ARCANA[n][0], ARCANA[n][1]
    return {"num": n, "name": name, "card": cid}


def matrix(d: dt.date, full: bool) -> dict:
    p = points(d)
    a = ARCANA[p["a"]]
    res = {"personal": {**card(p["a"]), "text": a[2], "plus": a[3]}, "full": full}
    if full:
        res["points"] = [
            {"title": "Таланты и дар", **card(p["b"]), "text": ARCANA[p["b"]][3]},
            {"title": "Деньги и реализация", **card(p["c"]), "text": ARCANA[p["c"]][5]},
            {"title": "Любовь и отношения", **card(p["love"]), "text": ARCANA[p["love"]][6]},
            {"title": "Предназначение", **card(p["purpose"]), "text": ARCANA[p["purpose"]][7]},
            {"title": "Кармический урок", **card(p["d"]), "text": ARCANA[p["d"]][4]},
            {"title": "Зона комфорта", **card(p["e"]), "text": ARCANA[p["e"]][2]},
        ]
    else:
        res["locked"] = ["Таланты и дар", "Деньги и реализация", "Любовь и отношения",
                         "Предназначение", "Кармический урок", "Зона комфорта"]
    return res


def compatibility(d1: dt.date, d2: dt.date) -> dict:
    p1, p2 = points(d1), points(d2)
    pair = reduce(p1["e"] + p2["e"])
    score = 62 + (p1["a"] * 7 + p2["a"] * 13 + pair * 5) % 34  # 62–95 %, всегда одинаково для одной пары
    t = ARCANA[pair]
    return {
        "score": score, "pair": {**card(pair), "text": t[6]},
        "you": card(p1["a"]), "partner": card(p2["a"]),
        "strength": t[3], "work": t[4],
    }
